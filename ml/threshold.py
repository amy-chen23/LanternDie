"""Select a provisional raw-score cutoff, then validate it on new insects."""
import argparse
import csv
import hashlib
import json
import math
from pathlib import Path

from scipy.stats import binomtest

from confidence import write_json


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def upper_error(errors, total, confidence):
    if total == 0:
        return None
    return float(binomtest(errors, total, alternative='less').proportion_ci(
        confidence_level=confidence, method='exact').high)


def counts(rows, threshold):
    alive = [r for r in rows if r['label'] == 'alive']
    dead = [r for r in rows if r['label'] == 'dead']
    fp = sum(r['score'] >= threshold for r in alive)
    tp = sum(r['score'] >= threshold for r in dead)
    return {'threshold': threshold, 'alive_tested': len(alive), 'dead_tested': len(dead),
            'alive_accepted_as_dead': fp, 'dead_accepted': tp,
            'observed_live_error_rate': fp / len(alive) if alive else None,
            'accepted_precision': tp / (tp + fp) if tp + fp else None,
            'community_review_count': len(rows) - tp - fp,
            'community_review_fraction': (len(rows) - tp - fp) / len(rows) if rows else None}


def read_scores(path):
    with path.open() as stream:
        rows = list(csv.DictReader(stream))
    if not rows or len({r['path'] for r in rows}) != len(rows):
        raise ValueError('Scores must contain unique image paths')
    for row in rows:
        row['score'] = float(row['raw_dead_score'])
        if row['label'] not in ('alive', 'dead') or not math.isfinite(row['score']) or not 0 <= row['score'] <= 1:
            raise ValueError('Invalid label or raw score')
    if {r['label'] for r in rows} != {'alive', 'dead'}:
        raise ValueError('Both labels are required')
    return rows


def analyze(data, target=0.01, confidence=0.95):
    source = data / '_work/model/out_of_fold.csv'
    model = data / '_work/mobile/lanternfly-dead.onnx'
    rows = read_scores(source)
    candidates = [counts(rows, i / 100) for i in range(70, 101)]
    eligible = [r for r in candidates if r['observed_live_error_rate'] <= target and r['dead_accepted'] > 0]
    selected = eligible[0] if eligible else None
    # These scores select the cutoff. They cannot also validate the selection,
    # and were generated by fold models, not by the final all-data model.
    policy = {
        'schema_version': 1, 'stage': 'provisional_requires_independent_validation',
        'model_sha256': digest(model), 'score': 'uncalibrated_dead_score',
        'threshold': selected['threshold'] if selected else None,
        'comparison': 'score >= threshold', 'below_threshold': 'community_verification',
        'invalid_score_or_no_crop': 'community_verification',
        'automatic_verification_enabled': False,
        'target_live_false_accept_rate': target, 'confidence_level': confidence,
        'selection_source_sha256': digest(source),
        'selection_method': 'Lowest cutoff on fixed 0.70..1.00 step-0.01 grid meeting the observed live-error target with nonzero dead coverage',
        'selection_counts_not_validation': selected,
        'zero_error_independent_live_specimens_needed': math.ceil(math.log(1-confidence) / math.log(1-target)),
        'warning': 'Threshold tuning only, not probability calibration. OOF selection counts are optimistic after tuning and do not validate the final model. Unknown specimen/session overlap remains possible.',
    }
    output = data / '_work/threshold'
    write_json(output / 'analysis.json', {
        'policy': policy, 'baseline': counts(rows, 0.70), 'candidates': candidates,
        'highest_live_oof_score': max(r['score'] for r in rows if r['label'] == 'alive'),
    })
    write_json(output / 'policy.json', policy)
    print(json.dumps(policy, indent=2))
    return policy


def validation_result(rows, policy):
    result = counts(rows, policy['threshold'])
    bound = upper_error(result['alive_accepted_as_dead'], result['alive_tested'], policy['confidence_level'])
    result.update(live_error_upper_bound=bound,
                  target_supported=bool(bound is not None and bound <= policy['target_live_false_accept_rate']
                                        and result['dead_tested'] > 0 and result['dead_accepted'] > 0))
    return result


def image_hash(path):
    from PIL import Image, ImageOps
    with Image.open(path) as source:
        image = ImageOps.exif_transpose(source).convert('RGB')
        return hashlib.sha256(str(image.size).encode() + image.tobytes()).hexdigest()


def validate(data, manifest, independent):
    if not independent:
        raise ValueError('Pass --independent-specimens only after confirming reviewed crops are new insects, one per group, not training/tuning specimens or sessions')
    import onnxruntime as ort
    from export_mobile import prepare_rgb
    policy_path = data / '_work/threshold/policy.json'
    policy = json.loads(policy_path.read_text())
    if policy['threshold'] is None:
        raise ValueError('No provisional cutoff could be selected')
    model = data / '_work/mobile/lanternfly-dead.onnx'
    if digest(model) != policy['model_sha256']:
        raise ValueError('The model has changed since cutoff selection; select a new policy and use a fresh validation set')
    with manifest.open() as stream:
        rows = list(csv.DictReader(stream))
    if not rows or not {'path', 'label', 'group'}.issubset(rows[0]):
        raise ValueError('Validation CSV requires path,label,group columns for reviewed insect crops')
    if any(not r['group'].strip() for r in rows) or len({r['group'] for r in rows}) != len(rows):
        raise ValueError('Use one reviewed crop per independent specimen/group for the binomial error bound')
    if {r['label'] for r in rows} != {'alive', 'dead'}:
        raise ValueError('Independent validation needs both alive and dead insects')
    with (data / '_work/manifest.csv').open() as stream:
        training = list(csv.DictReader(stream))
    known_hashes = {r['pixel_hash'] for r in training}
    known_groups = {r['group'] for r in training}
    known_prepared = set()
    for row in training:
        if row.get('crop') and (data / row['crop']).is_file():
            known_hashes.add(image_hash(data / row['crop']))
            known_prepared.add(hashlib.sha256(prepare_rgb(data / row['crop']).tobytes()).hexdigest())
    session = ort.InferenceSession(str(model), providers=['CPUExecutionProvider'])
    seen, prepared_seen, records = set(), set(), []
    for row in rows:
        path = (manifest.parent / row['path']).resolve()
        fingerprint = image_hash(path)
        pixels = prepare_rgb(path)
        prepared_hash = hashlib.sha256(pixels.tobytes()).hexdigest()
        if (fingerprint in known_hashes or fingerprint in seen or row['group'] in known_groups
                or prepared_hash in known_prepared or prepared_hash in prepared_seen):
            raise ValueError('Duplicate or training-overlap image/group in validation; use genuinely new specimens')
        seen.add(fingerprint)
        prepared_seen.add(prepared_hash)
        score = float(session.run(['dead_score'], {'rgb': pixels})[0].item())
        if not math.isfinite(score) or not 0 <= score <= 1:
            raise ValueError('Invalid inference output')
        records.append({**row, 'pixel_hash': fingerprint, 'score': score})
    result = validation_result(records, policy)
    report = {
        'stage': 'independent_fixed_cutoff_evaluation',
        'policy': policy, 'policy_sha256': digest(policy_path),
        'manifest_sha256': digest(manifest), 'results': result, 'images': records,
        'independent_specimens_attested': True,
        'warning': 'Exact overlap is checked; near-duplicates and shared sessions require human review. The bound assumes independent representative insects. Do not retune on these results and reuse this batch to claim validation. Phone performance and app routing are not tested.',
    }
    # Content-addressed reports preserve past evaluations rather than overwriting.
    key = hashlib.sha256(json.dumps(report, sort_keys=True).encode()).hexdigest()
    path = data / '_work/threshold/validations' / f'{key}.json'
    write_json(path, report)
    print(json.dumps({'report': str(path), **result}, indent=2))
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['analyze', 'validate'])
    parser.add_argument('--data', type=Path, default=Path('confidence-training'))
    parser.add_argument('--max-live-error', type=float, default=0.01)
    parser.add_argument('--confidence', type=float, default=0.95)
    parser.add_argument('--manifest', type=Path)
    parser.add_argument('--independent-specimens', action='store_true')
    args = parser.parse_args()
    if not 0 < args.max_live_error < 1 or not 0 < args.confidence < 1:
        parser.error('Error target and confidence must be between 0 and 1')
    try:
        if args.command == 'analyze':
            analyze(args.data, args.max_live_error, args.confidence)
        else:
            if args.manifest is None:
                parser.error('validate requires --manifest')
            validate(args.data, args.manifest, args.independent_specimens)
    except (ValueError, FileNotFoundError, KeyError) as error:
        parser.exit(1, f'{error}\n')


if __name__ == '__main__':
    main()
